import { useEffect, useState, type ReactNode } from 'react';
import { motion } from 'framer-motion';
import type { HeritageFeature } from '@heritagetrail/shared';
import { useApp } from '../state/AppContext.tsx';
import {
  CATEGORY_LABELS,
  flagExplanation,
  SOURCE_LABELS,
  UNESCO_LABELS,
  VERIFICATION_EXPLANATIONS,
  VERIFICATION_LABELS,
} from '../domain/categories.ts';
import { MAX_ROUTE_STOPS } from '../domain/routes.ts';
import { iconKeyFor } from '../map/categoryIcons.ts';
import { fetchSummary, type SummaryOutcome } from '../services/api.ts';
import { CategoryIcon } from './CategoryIcon.tsx';

function Row({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="grid grid-cols-[96px_1fr] gap-2 py-1.5 text-sm">
      <dt className="text-granite-500">{label}</dt>
      <dd className="min-w-0 text-granite-900">{children}</dd>
    </div>
  );
}

const ext = { target: '_blank', rel: 'noopener noreferrer' } as const;

function SummaryBlock({ feature }: { feature: HeritageFeature }) {
  const { config } = useApp();
  const [state, setState] = useState<{ loading: boolean; outcome: SummaryOutcome | null }>({ loading: false, outcome: null });
  useEffect(() => setState({ loading: false, outcome: null }), [feature.properties.id]);
  if (!config.summariesEnabled || !config.apiBaseUrl) return null;
  const apiBaseUrl = config.apiBaseUrl;
  const run = async () => {
    setState({ loading: true, outcome: null });
    setState({ loading: false, outcome: await fetchSummary(apiBaseUrl, feature.properties.id) });
  };
  const o = state.outcome;
  return (
    <section className="rounded-xl border border-indigo-heritage/20 bg-indigo-heritage/5 p-3">
      {!o && (
        <button
          type="button"
          onClick={run}
          disabled={state.loading}
          className="text-sm font-medium text-indigo-heritage hover:underline disabled:opacity-60"
        >
          {state.loading ? 'Generating summary…' : 'Generate AI summary from the stored sources'}
        </button>
      )}
      {o?.ok && (
        <div>
          <p className="mb-1 text-[11px] font-semibold uppercase tracking-[0.12em] text-indigo-heritage">
            AI-generated · {o.value.modelId}
          </p>
          <p className="whitespace-pre-line text-sm text-granite-800">{o.value.summary}</p>
          <p className="mt-1 text-[11px] text-granite-500">
            Generated by Amazon Bedrock from the source fields listed below only. Check the sources before relying on it.
          </p>
        </div>
      )}
      {o && !o.ok && (
        <p className="text-sm text-granite-600">
          {o.reason === 'insufficient_source_text'
            ? 'Not enough source text is stored for this site to write a grounded summary.'
            : 'The summary service is unavailable right now.'}
        </p>
      )}
    </section>
  );
}

export function DetailsPanel({ feature }: { feature: HeritageFeature }) {
  const { state, dispatch, byId } = useApp();
  const p = feature.properties;
  const [lon, lat] = feature.geometry.coordinates;
  const inRoute = state.route.stopIds.includes(p.id);
  const routeFull = state.route.stopIds.length >= MAX_ROUTE_STOPS;
  const statusColor =
    p.verificationStatus === 'verified' ? 'bg-emerald-700/10 text-emerald-800' : 'bg-laterite-100 text-laterite-700';

  return (
    <motion.aside
      key={p.id}
      role="dialog"
      aria-label={`Details: ${p.name}`}
      initial={{ opacity: 0, y: 24 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: 24 }}
      transition={{ type: 'spring', stiffness: 320, damping: 32 }}
      className="panel fixed inset-x-0 bottom-0 z-40 flex max-h-[78dvh] flex-col rounded-t-2xl md:absolute md:inset-x-auto md:bottom-10 md:right-4 md:top-4 md:max-h-none md:w-[400px] md:rounded-2xl"
    >
      {p.image && (
        <figure className="relative h-44 shrink-0 overflow-hidden rounded-t-2xl bg-granite-200">
          <img
            src={p.image.thumbUrl ?? p.image.url}
            alt={`Photograph of ${p.name}`}
            className="h-full w-full object-cover"
            loading="lazy"
            referrerPolicy="no-referrer"
          />
          <figcaption className="absolute inset-x-0 bottom-0 bg-gradient-to-t from-granite-900/85 to-transparent px-3 pb-1.5 pt-6 text-[11px] leading-tight text-ivory-100">
            {p.image.artist} ·{' '}
            {p.image.licenseUrl ? (
              <a href={p.image.licenseUrl} {...ext} className="underline">
                {p.image.license}
              </a>
            ) : (
              p.image.license
            )}{' '}
            ·{' '}
            <a href={p.image.filePageUrl} {...ext} className="underline">
              Wikimedia Commons
            </a>
          </figcaption>
        </figure>
      )}
      <div className="flex items-start gap-3 px-4 pb-2 pt-3">
        <CategoryIcon icon={iconKeyFor(p)} size={30} className="mt-1 shrink-0" />
        <div className="min-w-0 flex-1">
          <h2 className="font-display text-2xl font-semibold leading-tight text-granite-900">{p.name}</h2>
          <p className="text-xs text-granite-500">
            {[p.district, p.state].filter(Boolean).join(', ')} · {CATEGORY_LABELS[p.category]}
          </p>
        </div>
        <button
          type="button"
          onClick={() => dispatch({ type: 'select', id: null })}
          aria-label="Close details"
          className="-mr-1 rounded-full p-1.5 text-granite-500 hover:bg-ivory-200 hover:text-granite-900"
        >
          <svg viewBox="0 0 20 20" className="h-5 w-5" stroke="currentColor" strokeWidth="1.8" aria-hidden="true">
            <path d="M5 5l10 10M15 5L5 15" strokeLinecap="round" />
          </svg>
        </button>
      </div>

      <div className="flex flex-wrap gap-2 px-4 pb-3">
        <button
          type="button"
          onClick={() =>
            dispatch({ type: 'setNearbyCenter', center: feature.geometry.coordinates, label: p.name, siteId: p.id })
          }
          className="rounded-full bg-laterite-600 px-3 py-1.5 text-xs font-medium text-ivory-50 hover:bg-laterite-700"
        >
          Explore nearby
        </button>
        <button
          type="button"
          disabled={!inRoute && routeFull}
          onClick={() => dispatch(inRoute ? { type: 'removeStop', id: p.id } : { type: 'addStop', id: p.id })}
          className="rounded-full border border-laterite-600 px-3 py-1.5 text-xs font-medium text-laterite-700 hover:bg-laterite-50 disabled:opacity-50"
        >
          {inRoute ? 'Remove from route' : routeFull ? 'Route is full (25)' : 'Add to route'}
        </button>
      </div>
      <div className="ht-divider mx-4" />

      <div className="scroll-thin flex-1 space-y-4 overflow-y-auto px-4 pb-5 pt-2">
        <dl className="divide-y divide-granite-100">
          <Row label="Coordinates">
            <span className="tabular-nums">
              {lat.toFixed(5)}, {lon.toFixed(5)}
            </span>
          </Row>
          <Row label="State">{p.state}</Row>
          <Row label="District">{p.district ?? <span className="text-granite-500">unknown</span>}</Row>
          <Row label="Category">{CATEGORY_LABELS[p.category]}</Row>
          {p.unesco && (
            <Row label="UNESCO">
              {p.unescoUrl ? (
                <a href={p.unescoUrl} {...ext} className="text-indigo-heritage underline">
                  {UNESCO_LABELS[p.unesco]}
                </a>
              ) : (
                UNESCO_LABELS[p.unesco]
              )}
            </Row>
          )}
          {!p.unesco && p.unescoUrl && (
            <Row label="UNESCO">
              <a href={p.unescoUrl} {...ext} className="text-indigo-heritage underline">
                World Heritage List entry
              </a>
            </Row>
          )}
          {p.designations.length > 0 && <Row label="Designation">{p.designations.join('; ')}</Row>}
          {p.asiMonumentId && <Row label="ASI ID">{p.asiMonumentId}</Row>}
          <Row label="Period">
            {p.period ? (
              <>
                {p.period.label} <span className="text-xs text-granite-500">({p.period.source})</span>
              </>
            ) : (
              <span className="text-granite-500">unknown</span>
            )}
          </Row>
        </dl>

        <section>
          <h3 className="mb-1 font-display text-lg font-semibold">History</h3>
          {p.description ? (
            <p className="text-sm text-granite-800">
              {p.description.text}{' '}
              <span className="text-xs text-granite-500">
                (
                <a href={p.description.source} {...ext} className="underline">
                  source
                </a>
                , {p.description.license})
              </span>
            </p>
          ) : (
            <p className="text-sm text-granite-500">No description is available in the sources.</p>
          )}
        </section>

        <SummaryBlock feature={feature} />

        <section>
          <h3 className="mb-1 font-display text-lg font-semibold">Sources</h3>
          <ul className="space-y-1 text-sm">
            {p.sources.map((s) => (
              <li key={`${s.name}-${s.id}`} className="flex flex-wrap items-baseline gap-x-1.5">
                <a href={s.url} {...ext} className="font-medium text-laterite-700 underline">
                  {SOURCE_LABELS[s.name] ?? s.name} {s.id}
                </a>
                <a href={s.licenseUrl} {...ext} className="text-xs text-granite-500 underline">
                  {s.license}
                </a>
                <span className="text-xs text-granite-500">retrieved {s.retrievedAt.slice(0, 10)}</span>
              </li>
            ))}
            {p.image && (
              <li className="flex flex-wrap items-baseline gap-x-1.5">
                <a href={p.image.filePageUrl} {...ext} className="font-medium text-laterite-700 underline">
                  Wikimedia Commons image
                </a>
                <span className="text-xs text-granite-500">
                  {p.image.license}, {p.image.artist}
                  {p.image.credit ? ` (${p.image.credit})` : ''}
                </span>
              </li>
            )}
          </ul>
          <p className="mt-1 text-xs text-granite-500">Record licence: {p.license}</p>
        </section>

        <section>
          <h3 className="mb-1 font-display text-lg font-semibold">Verification</h3>
          <span className={`inline-block rounded-full px-2.5 py-0.5 text-xs font-semibold ${statusColor}`}>
            {VERIFICATION_LABELS[p.verificationStatus]}
          </span>
          <p className="mt-1 text-xs text-granite-600">{VERIFICATION_EXPLANATIONS[p.verificationStatus]}</p>
          {p.flags.length > 0 && (
            <ul className="mt-2 space-y-1">
              {p.flags.map((flag) => (
                <li key={flag} className="text-xs text-granite-700">
                  <code className="mr-1 rounded bg-ivory-200 px-1 py-0.5 text-[10px] text-granite-800">
                    {flag.startsWith('possible-duplicate:') ? 'possible-duplicate' : flag}
                  </code>
                  {flagExplanation(flag)}
                  {flag.startsWith('possible-duplicate:') && byId.has(flag.slice('possible-duplicate:'.length)) && (
                    <button
                      type="button"
                      onClick={() => dispatch({ type: 'select', id: flag.slice('possible-duplicate:'.length) })}
                      className="ml-1 text-laterite-700 underline"
                    >
                      View {byId.get(flag.slice('possible-duplicate:'.length))!.properties.name}
                    </button>
                  )}
                </li>
              ))}
            </ul>
          )}
        </section>
      </div>
    </motion.aside>
  );
}
